import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:inkflow/constants.dart';
import 'package:inkflow/screens/loading_screen.dart';
import 'package:inkflow/screens/welcome_screen.dart';
import 'package:inkflow/screens/login_screen.dart'; // Import your SignInScreen
import 'package:firebase_core/firebase_core.dart';
import 'firebase_options.dart'; // Ensure this file is generated by flutterfire configure

void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Initialize Firebase with platform-specific options
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );

  runApp(MyApp());
}

class MyApp extends StatefulWidget {
  @override
  _MyAppState createState() => _MyAppState();
}

class _MyAppState extends State<MyApp> {
  bool _isLoading = true;
  bool _isLoggedIn = false;
  bool _isFirstOpen = true; // To track if the app is opened for the first time

  @override
  void initState() {
    super.initState();
    _checkLoginStatus();
  }

  // Check the login status using SharedPreferences
  Future<void> _checkLoginStatus() async {
    SharedPreferences prefs = await SharedPreferences.getInstance();

    // Check if it's the user's first time opening the app
    _isFirstOpen = prefs.getBool('isFirstOpen') ?? true;

    if (_isFirstOpen) {
      // Set the first open flag to false after the first launch
      await prefs.setBool('isFirstOpen', false);
    }

    bool? isLoggedIn = prefs.getBool('isLoggedIn') ?? false;

    setState(() {
      _isLoggedIn = isLoggedIn;
      _isLoading = false; // Finish loading
    });
  }

  @override
  Widget build(BuildContext context) {
    if (_isLoading) {
      // Show a loading spinner while checking the login status
      return MaterialApp(
        debugShowCheckedModeBanner: false,
        title: 'Book App',
        theme: ThemeData(
          scaffoldBackgroundColor: Colors.white,
          textTheme: Theme.of(context).textTheme.apply(
                displayColor: kBlackColor,
              ),
        ),
        home: Scaffold(
          backgroundColor: kScaffoldBackgroundColor,
        ),
      );
    }

    // Decide the initial screen based on login status
    // Redirect to SignInScreen if not logged in and not the first time
    if (!_isLoggedIn && !_isFirstOpen) {
      return MaterialApp(
        debugShowCheckedModeBanner: false,
        title: 'Book App',
        theme: ThemeData(
          scaffoldBackgroundColor: Colors.white,
          textTheme: Theme.of(context).textTheme.apply(
                displayColor: kBlackColor,
              ),
        ),
        home: LoginScreen(), // Redirect to the SignInScreen
      );
    }

    return MaterialApp(
      debugShowCheckedModeBanner: false,
      title: 'Book App',
      theme: ThemeData(
        scaffoldBackgroundColor: Colors.white,
        textTheme: Theme.of(context).textTheme.apply(
              displayColor: kBlackColor,
            ),
      ),
      home: _isLoggedIn ? LoadingScreen() : WelcomeScreen(),
    );
  }
}
